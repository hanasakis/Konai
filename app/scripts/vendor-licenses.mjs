// Konai license gate: scan runtime dependencies for Copyleft licenses and emit a report.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const ROOT = path.resolve(__dirname, '..')
const ALLOWED = ['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'OFL-1.1', 'CC0-1.0', 'Unlicense', 'Python-2.0', 'MPL-2.0', '0BSD']
const COPYLEFT = ['GPL-2.0', 'GPL-3.0', 'LGPL-2.1', 'LGPL-3.0', 'AGPL-3.0', 'GPL', 'AGPL', 'LGPL', 'SSPL-1.0', 'CC-BY-SA-4.0']

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) { if (e.name === 'node_modules') continue; walk(p, out) }
    else if (e.name === 'package.json') out.push(p)
  }
  return out
}

const nm = path.join(ROOT, 'node_modules')
const pkgs = []
for (const name of fs.readdirSync(nm)) {
  if (name.startsWith('.')) continue
  const scope = name.startsWith('@')
  const dirs = scope ? fs.readdirSync(path.join(nm, name)).map((n) => path.join(nm, name, n)) : [path.join(nm, name)]
  for (const d of dirs) {
    const pj = path.join(d, 'package.json')
    if (fs.existsSync(pj)) {
      try {
        const j = JSON.parse(fs.readFileSync(pj, 'utf8'))
        const lic = j.license || (j.licenses && j.licenses[0] && j.licenses[0].type) || 'UNKNOWN'
        pkgs.push({ name: j.name || path.basename(d), version: j.version || '', license: lic })
      } catch { /* ignore */ }
    }
  }
}

const bad = pkgs.filter((p) => COPYLEFT.some((c) => String(p.license).toUpperCase().includes(c.toUpperCase())))
const unknown = pkgs.filter((p) => String(p.license) === 'UNKNOWN')
const lines = ['# Konai third-party license report', '', 'Generated by scripts/vendor-licenses.mjs', '', '| Package | Version | License |', '| --- | --- | --- |']
for (const p of pkgs.sort((a, b) => a.name.localeCompare(b.name))) lines.push('| ' + p.name + ' | ' + p.version + ' | ' + p.license + ' |')
lines.push('', 'Copyleft matches: ' + bad.length, 'Unknown: ' + unknown.length)
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_LICENSES.md'), lines.join('\n') + '\n')
console.log('packages scanned:', pkgs.length)
console.log('copyleft matches:', bad.length)
for (const b of bad) console.log('  COPYLEFT', b.name, b.license)
console.log('unknown licenses:', unknown.length)
for (const u of unknown.slice(0, 20)) console.log('  UNKNOWN', u.name)
console.log('report: THIRD_PARTY_LICENSES.md')
process.exit(bad.length ? 1 : 0)